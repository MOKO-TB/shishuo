function startOfLocalDay(ts: number) {
  const date = new Date(ts)
  date.setHours(0, 0, 0, 0)
  return date.getTime()
}

export function dateKey(ts: number) {
  const date = new Date(ts)
  const month = `${date.getMonth() + 1}`.padStart(2, '0')
  const day = `${date.getDate()}`.padStart(2, '0')
  return `${date.getFullYear()}-${month}-${day}`
}

function dailyMetrics(now: number): DailyMetric[] {
  const ai = [12, 9, 15, 18, 14, 21, 23]
  const human = [4, 5, 3, 5, 4, 6, 7]
  return ai.map((count, index) => ({
    date: dateKey(now - (6 - index) * DAY),
    ai: count,
    human: human[index],
  }))
}

