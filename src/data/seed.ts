let extraCourses: Course[] = []

/** Courses generated from the student's real timetable; replaced on every profile update. */
export function registerExtraCourses(courses: Course[]) {
  extraCourses = courses.slice()
}

export function allCourses() {
  return extraCourses.length > 0 ? [...COURSES, ...extraCourses] : COURSES
}

export function isSeededCourse(id: string) {
  return COURSES.some((course) => course.id === id)
}

export function courseById(id: string): Course {
  if (id === CAMPUS_COURSE_ID) return CAMPUS_COURSE
  return (
    allCourses().find((course) => course.id === id) ?? {
      id,
      name: '未命名课程',
      shortName: '未命名课程',
      code: '',
      teacher: '未指定',
      teacherTitle: '任课教师',
      accent: 'gold',
      students: 0,
      chapter: '',
    }
  )
}

export function allTeachers(): TeacherProfile[] {
  const teachers = TEACHERS.map((teacher) => ({ ...teacher, courses: [...teacher.courses] }))
  const byName = new Map(teachers.map((teacher) => [teacher.name, teacher]))
  for (const course of extraCourses) {
    const name = course.teacher || '未指定'
    let teacher = byName.get(name)
    if (!teacher) {
      teacher = {
        id: `jw-teacher-${name}`,
        name,
        title: course.teacherTitle || '任课教师',
        meta: course.shortName,
        courses: [],
        accent: course.accent,
      }
      byName.set(name, teacher)
      teachers.push(teacher)
    }
    if (!teacher.courses.includes(course.id)) teacher.courses.push(course.id)
    if (!TEACHERS.some((item) => item.name === name)) {
      teacher.meta = teacher.courses
        .map((courseId) => allCourses().find((item) => item.id === courseId)?.shortName)
        .filter(Boolean)
        .join(' · ')
    }
  }
  return teachers
}

export function teacherByName(name: string) {
  return allTeachers().find((teacher) => teacher.name === name) ?? allTeachers()[0]
}

export function isSeededTeacher(name: string) {
  return TEACHERS.some((teacher) => teacher.name === name)
}

