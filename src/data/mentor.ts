const dynamicMentors = new Map<string, CourseMentor>()

export function availableMentors() {
  const known = new Set(COURSE_MENTORS.map((mentor) => mentor.courseId))
  for (const course of allCourses()) {
    if (known.has(course.id)) continue
    const key = `${course.id}::${course.teacher}::${course.shortName}`
    if (!dynamicMentors.has(key)) dynamicMentors.set(key, mentorFromCourse(course))
  }
  return [...COURSE_MENTORS, ...dynamicMentors.values()]
}

export function mentorForCourse(courseId: string): CourseMentor | undefined {
  return availableMentors().find((mentor) => mentor.courseId === courseId)
}

/** 导师对应的任课教师（用于界面上的一一对应展示）。 */
export function mentorTeacherName(mentor: CourseMentor) {
  const teacher = courseById(mentor.courseId).teacher
  return teacher && teacher !== '未指定' ? teacher : ''
}

function normalize(text: string) {
  return text.toLowerCase().replace(/[\s\p{P}\p{S}]/gu, '')
}

export function findMentorTopic(
  mentor: CourseMentor,
  faq: { id: string; question: string; tags: string[] },
  question: string,
): MentorTopic | undefined {
  const byFaq = mentor.topics.find((topic) => topic.faqIds.includes(faq.id))
  if (byFaq) return byFaq

  const haystack = normalize(`${faq.question} ${faq.tags.join(' ')} ${question}`)
  return mentor.topics.find((topic) =>
    topic.aliases.some((alias) => haystack.includes(normalize(alias))),
  )
}

export function findMentorTopicByQuestion(
  mentor: CourseMentor,
  question: string,
): MentorTopic | undefined {
  const key = normalize(question)
  if (!key) return undefined
  let best: { topic: MentorTopic; score: number } | undefined
  for (const topic of mentor.topics) {
    for (const alias of [topic.name, ...topic.aliases]) {
      const candidate = normalize(alias)
      if (candidate.length < 2 || !key.includes(candidate)) continue
      if (!best || candidate.length > best.score) {
        best = { topic, score: candidate.length }
      }
    }
  }
  return best?.topic
}

export function buildMentorPrompt(mentor: CourseMentor, question: string) {
  const topic = findMentorTopicByQuestion(mentor, question)
  const chapter = mentor.chapters.find((item) => question.includes(item.label))
  const style = mentor.styleNotes.slice(0, 3).map((note) => `- ${note}`).join('\n')
  const voice = mentor.voice?.prompt ? `\n说话方式：${mentor.voice.prompt}` : ''
  const principles = mentor.principles.map((item) => `- ${item}`).join('\n')
  const map = mentor.chapters
    .map((item) => `- ${item.label}：${item.topics.slice(0, 4).join('、')}`)
    .join('\n')
  const focus = topic
    ? [
        `本轮匹配到的卡点：${topic.name}`,
        `先修：${topic.prerequisite}`,
        `核心：${topic.core}`,
        `例子：${topic.example}`,
        `诊断问题：${topic.diagnose.join('；')}`,
        `关键动作：${topic.moves.join('；')}`,
        `误区：${topic.misconception.wrong} / ${topic.misconception.why} / 改法：${topic.misconception.fix}`,
        `迁移题：${topic.transfer.question}（提示：${topic.transfer.hint}；答案不要直接给）`,
      ].join('\n')
    : chapter
      ? `本轮匹配到章节：${chapter.label}\n建议：${chapter.advice}\n主题：${chapter.topics.join('、')}`
      : '没有匹配到具体主题。先诊断学生卡在哪一层，再给下一步；不要硬套一个章节。'

  return `你是${mentor.name}（${mentor.title}课程 AI 导师），不是通用问答。${mentor.tagline}

教学法原则：
${principles}

讲课风格：
${style}${voice}

课程地图：
${map}

先修补强：
${mentor.foundation.map((item, index) => `${index + 1}. ${item}`).join('\n')}

${focus}

回答要求：
1. 用中文，像这位老师在课后答疑：先给位置感/卡点，再讲关键一步，不要先堆通用定义。
2. 先做一次诊断（问一个关键问题或点明类型），再给先修检查；如果学生只是打招呼，用一两句话把话题拉回“你现在卡在哪”。
3. 只讲最关键的一步“为什么可以”，给一个反例或边界；不要把所有步骤一次倒完。
4. 结尾留一道换数字的迁移题，不要直接给答案；可以给提示。
5. 数学公式用 $...$ 包裹，不要用代码块或裸露的 ^{} / _{}；不用 Markdown 表格。
6. 学生可能没看过公开课视频：不要用“第几集”“P 编号”这类集数定位，也不要问“学到哪一集”；需要确认进度时，只给 2–3 个章节名或主题让学生选。
7. 不冒充任课老师，不编“老师说过”或课程引用；不确定就建议转交任课老师。控制在 600 字以内。`
}

